"""The final report — the artifact a human actually reads.

Two design rules, both non-obvious and both deliberate:

**Rejected findings appear in the report.** A report showing only what survived is not an
audit; it is a highlight reel. `REJECTED_FINDINGS` is a required section precisely because
the temptation to drop it is strong.

**Facts are injected, prose is generated.** The model writes narrative only inside sections
whose numbers, confidences and evidence references are already fixed. Nothing in a report is
regenerated by a model at render time, which is why a report can be reproduced byte-identical
from stored state.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum

from pydantic import Field, model_validator

from app.schemas.common import JarvisModel, NonEmptyStr, RunId, UnitFloat, utcnow
from app.schemas.evidence import EvidenceGap
from app.schemas.execution import RunStatus, TerminationReason
from app.schemas.finding import Finding


class SectionKind(StrEnum):
    """The report's fixed structure. Order here is presentation order."""

    EXECUTIVE_SUMMARY = "EXECUTIVE_SUMMARY"
    INVESTIGATION_SCOPE = "INVESTIGATION_SCOPE"
    EXECUTION_SUMMARY = "EXECUTION_SUMMARY"
    VERIFIED_FINDINGS = "VERIFIED_FINDINGS"
    EVIDENCE = "EVIDENCE"
    UNCERTAIN_FINDINGS = "UNCERTAIN_FINDINGS"
    REJECTED_FINDINGS = "REJECTED_FINDINGS"
    REASONING = "REASONING"
    ACTIONS_PERFORMED = "ACTIONS_PERFORMED"
    CONFIDENCE = "CONFIDENCE"
    LIMITATIONS = "LIMITATIONS"


REQUIRED_SECTIONS: tuple[SectionKind, ...] = tuple(SectionKind)


class ReportSection(JarvisModel):
    """One section. `narrative` is model-written; everything else is injected."""

    kind: SectionKind
    heading: NonEmptyStr
    narrative: str = ""
    # Structured content the renderer lays out: finding ids, counts, tables.
    items: list[str] = Field(default_factory=list)
    finding_ids: list[str] = Field(default_factory=list)


class ExecutionSummary(JarvisModel):
    """What the run actually did. Every field is counted, never estimated."""

    tasks_planned: int = Field(default=0, ge=0)
    tasks_completed: int = Field(default=0, ge=0)
    tasks_failed: int = Field(default=0, ge=0)
    tasks_skipped: int = Field(default=0, ge=0)
    tool_calls: int = Field(default=0, ge=0)
    documents_processed: int = Field(default=0, ge=0)
    replan_iterations: int = Field(default=0, ge=0)
    gaps_detected: int = Field(default=0, ge=0)
    gaps_resolved: int = Field(default=0, ge=0)
    duration_ms: int = Field(default=0, ge=0)


class Limitation(JarvisModel):
    """Something that constrains how much the report can be trusted.

    Generated from run facts — skipped tasks, unresolved gaps, degraded verification,
    exhausted budget — not from the model's sense of modesty.
    """

    description: NonEmptyStr
    cause: str = ""


class FinalReport(JarvisModel):
    """The structured investigation report."""

    run_id: RunId
    objective: NonEmptyStr
    sections: list[ReportSection] = Field(default_factory=list)

    verified_findings: list[Finding] = Field(default_factory=list)
    uncertain_findings: list[Finding] = Field(default_factory=list)
    rejected_findings: list[Finding] = Field(default_factory=list)
    unresolved_gaps: list[EvidenceGap] = Field(default_factory=list)

    execution: ExecutionSummary = Field(default_factory=ExecutionSummary)
    limitations: list[Limitation] = Field(default_factory=list)

    # Mean computed confidence across verified findings.
    overall_confidence: UnitFloat = 0.0
    generated_at: datetime = Field(default_factory=utcnow)

    @property
    def total_findings(self) -> int:
        return (
            len(self.verified_findings) + len(self.uncertain_findings) + len(self.rejected_findings)
        )

    def section(self, kind: SectionKind) -> ReportSection | None:
        return next((s for s in self.sections if s.kind is kind), None)

    @model_validator(mode="after")
    def _every_verified_finding_has_evidence(self) -> FinalReport:
        """The report cannot present an unsupported claim as verified.

        This is the last line of defence before a human reads the output. If it ever fires,
        something upstream has gone badly wrong and the run should fail loudly rather than
        publish.
        """
        unsupported = [f.finding_id for f in self.verified_findings if not f.has_resolved_evidence]
        if unsupported:
            raise ValueError(
                f"verified findings without resolved evidence: {unsupported} - "
                "an evidence-driven report cannot present these as verified"
            )
        return self


class AgentResult(JarvisModel):
    """What a completed run returns: the report plus the facts about the run itself."""

    run_id: RunId
    status: RunStatus
    report: FinalReport | None = None
    termination_reason: TerminationReason | None = None
    error_code: str = ""
    error_message: str = ""
    started_at: datetime | None = None
    completed_at: datetime | None = None

    @property
    def succeeded(self) -> bool:
        return self.status in {RunStatus.COMPLETED, RunStatus.COMPLETED_WITH_GAPS}

    @model_validator(mode="after")
    def _outcomes_are_consistent(self) -> AgentResult:
        if self.succeeded and self.report is None:
            raise ValueError(f"status={self.status.value} requires a report")
        if self.status is RunStatus.FAILED and not self.error_code:
            raise ValueError("a failed run must carry an error_code")
        return self
